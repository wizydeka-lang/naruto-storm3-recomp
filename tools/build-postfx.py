#!/usr/bin/env python3
"""Compile the native view's post-processing shaders (src/shaders) to SPIR-V.

FSR 1 (fsr1.hlsl), CAS (cas.hlsl), FXAA (fxaa.hlsl) and the 24-bit depth
conversion for depth resolves (depth24.hlsl). Writes
src/postfx_spirv.h, which is committed so builds (Android included) need no
shader compiler. Run this after changing a shader. Uses the DXC that
tools/build-shaders.py downloads with XenosRecomp (run that first).

Usage: python3 tools/build-postfx.py
"""

import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DXC_DIR = ROOT / "out" / "tools" / "XenosRecomp" / "thirdparty" / "dxc-bin"
SHADERS = ROOT / "src" / "shaders"
OUTPUT = ROOT / "src" / "postfx_spirv.h"
THIRD_PARTY = ROOT / "third_party"
# Array name, shader, defines.
STAGES = [
    ("kFsrEasuSpirv", "fsr1.hlsl", ["EASU=1"]),
    ("kFsrRcasSpirv", "fsr1.hlsl", ["EASU=0"]),
    ("kCasSpirv", "cas.hlsl", ["CAS_SCALE=0"]),
    ("kCasScaleSpirv", "cas.hlsl", ["CAS_SCALE=1"]),
    ("kFxaaSpirv", "fxaa.hlsl", []),
    ("kDepth24Spirv", "depth24.hlsl", []),
]
INCLUDES = [THIRD_PARTY / "ffx-fsr", THIRD_PARTY / "ffx-cas", THIRD_PARTY / "fxaa"]


def main():
    dxc = DXC_DIR / "bin" / "x64" / "dxc-linux"
    if not dxc.exists():
        sys.exit(f"{dxc} not found; run tools/build-shaders.py first.")
    env = dict(os.environ, LD_LIBRARY_PATH=str(DXC_DIR / "lib" / "x64"))
    arrays = []
    with tempfile.TemporaryDirectory() as tmp:
        for name, shader, defines in STAGES:
            spirv = Path(tmp) / f"{name}.spv"
            command = [str(dxc), "-T", "cs_6_0", "-E", "main", "-HV", "2018", "-spirv",
                       "-fspv-target-env=vulkan1.1", "-Qstrip_debug", "-O3"]
            command += [f"-D{define}" for define in defines]
            for include in INCLUDES:
                command += ["-I", str(include)]
            command += [str(SHADERS / shader), "-Fo", str(spirv)]
            subprocess.run(command, env=env, check=True)
            data = spirv.read_bytes()
            words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
            lines = [", ".join(f"0x{w:08x}" for w in words[i:i + 8])
                     for i in range(0, len(words), 8)]
            arrays.append(f"inline constexpr uint32_t {name}[] = {{\n    "
                          + ",\n    ".join(lines) + "};\n")
    OUTPUT.write_text(
        "// naruto - post-processing shaders for the native view, as SPIR-V.\n"
        "// Generated by tools/build-postfx.py from src/shaders; do not edit.\n\n"
        "#pragma once\n\n#include <cstdint>\n\n" + "\n".join(arrays))
    print(f"{OUTPUT}: {sum(len(a) for a in arrays)} characters")


if __name__ == "__main__":
    main()
